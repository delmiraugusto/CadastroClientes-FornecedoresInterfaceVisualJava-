    private void buAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buAlterarActionPerformed
        int indiceFornecedor = tabelaPessoa.getSelectedRow();
        if (indiceFornecedor >= 0){
            Fornecedor fornecedor = modeloPessoa.obterFornecedor(indiceFornecedor); 
            if (JanelaCadastroFornecedor.executar(null, OperacaoCadastro.ocAlterar, fornecedor)) {
                modeloPessoa.atualizarPessoa(indiceFornecedor, fornecedor);
                ArquivoClienteFornecedor.salvarFornecedoresArquivo(modeloPessoa.getListaFornecedores());
            }
        } else {
            JOptionPane.showMessageDialog(null, "É necessário selecionar a passoa.");
        }
    }//GEN-LAST:event_buAlterarActionPerformed

    private void buExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buExcluirActionPerformed
        int opcao = JOptionPane.showConfirmDialog(null, 
        "Tem certeza que deseja excluir o cliente?", 
        "Confirmar Exclusão", 
        JOptionPane.YES_NO_OPTION);

        if (opcao == JOptionPane.YES_OPTION) {
            int indiceFornecedor = tabelaPessoa.getSelectedRow();
        if (indiceFornecedor >= 0){
            modeloPessoa.excluirPessoa(indiceFornecedor);
            ArquivoClienteFornecedor.salvarFornecedoresArquivo(modeloPessoa.getListaFornecedores());
        } else {
            JOptionPane.showMessageDialog(null, "É necessário selecionar o fornecedor.");
        }
            System.out.println("Cliente excluído.");
        } else {
            System.out.println("Exclusão cancelada.");
        }

        
        
    }//GEN-LAST:event_buExcluirActionPerformed

