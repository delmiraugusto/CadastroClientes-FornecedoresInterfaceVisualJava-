    private void buIncluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buIncluirActionPerformed
        Fornecedor fornecedor = new Fornecedor();
        if (JanelaCadastroFornecedor.executar(null, OperacaoCadastro.ocIncluir, fornecedor)) {
            modeloPessoa.incluirPessoa(fornecedor);
            ArquivoClienteFornecedor.salvarFornecedoresArquivo(modeloPessoa.getListaFornecedores());
        }
    }//GEN-LAST:event_buIncluirActionPerformed

