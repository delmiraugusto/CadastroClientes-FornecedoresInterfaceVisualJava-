    private void buOk4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buOk4ActionPerformed
        if (operacaoCadastro != OperacaoCadastro.ocConsultar){
            cliente.setNome(edNome.getText());
            cliente.setTelefone(edTelefone.getText());
            cliente.setCpf(edCPF.getText());
            cliente.setEmail(edEmail.getText());
            cliente.setCep(edCep.getText());
            cliente.setEstado(edEstado.getSelectedItem().toString());
            cliente.setLogradouro(edLogradouro.getText());
            cliente.setNumero(edNumero.getText());
            cliente.setComplemento(edComplemento.getText());
            cliente.setBairro(edBairro.getText());
            cliente.setCidade(edCidade.getText());
            confirmado = true;
        }
        dispose();
    }//GEN-LAST:event_buOk4ActionPerformed

