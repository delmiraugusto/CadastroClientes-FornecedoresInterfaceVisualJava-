    public static boolean executar(java.awt.Frame parent,
                                   OperacaoCadastro operacaoCadastro,
                                   Cliente cliente){
        
      JanelaCadastroCliente frmPessoa = new JanelaCadastroCliente(parent,operacaoCadastro, cliente);
      frmPessoa.setLocationRelativeTo(null);
      frmPessoa.setVisible(true);
      return frmPessoa.operacaoConfirmada();     
}
    public JanelaCadastroCliente(java.awt.Frame parent,
                     OperacaoCadastro operacaoCadastro,
                     Cliente cliente){
        super (parent, true);
        confirmado = false;
        this.operacaoCadastro = operacaoCadastro;
        this.cliente = cliente;
        
        initComponents();
        
        edEstado.removeAllItems();
        String[] estados = {
            "AC", "AL", "AP", "AM", "BA", "CE", "DF", "ES", "GO", "MA",
            "MT", "MS", "MG", "PA", "PB", "PR", "PE", "PI", "RJ", "RN",
            "RS", "RO", "RR", "SC", "SP", "SE", "TO"
        };

        for (String estado : estados) {
            edEstado.addItem(estado);
        }

        
        if (operacaoCadastro == OperacaoCadastro.ocAlterar ||
            operacaoCadastro == OperacaoCadastro.ocConsultar){
            edNome.setText(cliente.getNome());
            edTelefone.setText(cliente.getTelefone());
            edEmail.setText(cliente.getEmail());
            edCPF.setText(cliente.getCpf());
            edLogradouro.setText(cliente.getLogradouro());
            edNumero.setText(cliente.getNumero());
            edComplemento.setText(cliente.getComplemento());
            edBairro.setText(cliente.getBairro());
            edCidade.setText(cliente.getCidade());
            edEstado.setSelectedItem(cliente.getEstado());
            edCep.setText(cliente.getCep());
        }
        
        buCancelar.setVisible(operacaoCadastro != OperacaoCadastro.ocConsultar);
        edNome.setEnabled(operacaoCadastro != OperacaoCadastro.ocConsultar);
        edTelefone.setEnabled(operacaoCadastro != OperacaoCadastro.ocConsultar);
        
        
    }
    
    public boolean operacaoConfirmada(){
        return confirmado;
    }

